def is_resume(content: str) -> bool:
    return bool(
        re.fullmatch(
            r"\s*(?:続き|続きを(?:お願い(?:します)?|実行|再開|分析)?|続けて(?:ください)?|再開(?:して)?|残りを(?:実行|分析)(?:してください)?)[。！!\s]*",
            content,
        )
    )


def explicit_grouped_request(content: str) -> GroupedRequest | None:
    """Fallback for the unambiguous page-then-source example; no bare cross query."""
    top = re.search(r"(?:上位|top)\s*(\d{1,2})", content, re.I)
    if not top or not re.search(
        r"各ページ|それぞれのページ|ページごと|ページ別|各々|"
        r"(?:その|上位)\s*(?:\d+\s*)?ページ[、,\s]*(?:の)?それぞれ",
        content,
    ):
        return None
    if not re.search(r"参照元|流入元|source", content, re.I):
        return None
    count = int(top[1])
    if not 1 <= count <= 10:
        return None
    return GroupedRequest(primary="page_path", secondary="session_source", limit=count)


def create_staged(
    request: GroupedRequest,
    base: IntentPlan,
    state: AnalysisState,
    definitions: list[SemanticDefinition],
    objective: str,
) -> StagedPlan:
    terms = {d.canonical_name: d for d in definitions if d.enabled and d.available}
    primary, secondary = terms.get(request.primary), terms.get(request.secondary)
    metrics = base.metric_terms or state.metrics
    if (
        not primary
        or not secondary
        or primary.kind != "dimension"
        or secondary.kind != "dimension"
        or primary == secondary
        or len(metrics) != 1
        or metrics[0] not in terms
    ):
        raise ValueError("grouped_analysis_requires_two_dimensions_one_metric")
    if base.visualization_only or base.skill_id in {
        AnalysisSkillId.FUNNEL,
        AnalysisSkillId.REALTIME,
        AnalysisSkillId.ANOMALY_SCAN,
    }:
        raise ValueError("grouped_analysis_requires_core_report")
    metric = terms[metrics[0]]
    # Ranking baseline must be an exact, single period. Multi-period per-entity
    # comparisons need a separate contract; never silently remove that request.
    if (
        base.comparison_period
        or base.comparison is not ComparisonIntent.NONE
        or (
            state.comparison_period
            and not base.clear_comparison
            and (base.period is None or base.period == state.period)
        )
    ):
        raise ValueError("grouped_analysis_single_period_required")
    if not primary.ga4_mapping or not secondary.ga4_mapping or not metric.ga4_mapping:
        raise ValueError("grouped_analysis_unregistered_mapping")
    rank = base.model_copy(
        update={
            "dimension_terms": (request.primary,),
            "metric_terms": metrics,
            "skill_id": AnalysisSkillId.BREAKDOWN_RANK,
            "time_grain": None,
            "ranking": RankingIntent(limit=request.limit),
            "intent": "上位対象を単独集計で確定",
            "preferred_chart_type": base.preferred_chart_type or "bar",
        }
    )
    return StagedPlan(
        objective=objective[:500],
        request=request,
        primary_field=primary.ga4_mapping["dimension"],
        secondary_field=secondary.ga4_mapping["dimension"],
        metric_field=metric.ga4_mapping["metric"],
        rank_plan=rank,
        anchor=AnalysisState(
            data_source_set_id=state.data_source_set_id, **query_context(state)
        ),
    )


def next_query(
    staged: StagedPlan,
) -> tuple[IntentPlan, tuple[AnalysisFilter, ...]] | None:
    if staged.phase not in {"rank", "children"}:
        return None
    filters = list(staged.anchor.filters)
    if staged.phase == "rank":
        return staged.rank_plan, tuple(
            f for f in filters if f.semantic_name.startswith("observed_")
        )
    item = next((i for i in staged.items if i.status == "pending"), None)
    if item is None:
        return None
    narrowing = AnalysisFilter(
        semantic_name=observed_name(staged.primary_field, item.value),
        kind="filter",
        field_name=staged.primary_field,
        value=item.value,
    )
    # Exact values are bound from the rank result, never generated by the LLM.
    filters = [f for f in filters if f.field_name != staged.primary_field] + [narrowing]
    return staged.rank_plan.model_copy(
        update={
            "intent": "確定した対象ごとの内訳を調査",
            "period": staged.anchor.period,
            "comparison_period": None,
            "comparison": ComparisonIntent.NONE,
            "clear_comparison": True,
            "clear_filters": True,
            "channel_term": None,
            "device_term": None,
            "filter_terms": tuple(f.semantic_name for f in filters),
            "dimension_terms": (staged.request.secondary,),
            "ranking": RankingIntent(limit=5),
        }
    ), tuple(f for f in filters if f.semantic_name.startswith("observed_"))


def record_result(
    staged: StagedPlan,
    rows: tuple[dict[str, Any], ...] | list[dict[str, Any]],
    state: AnalysisState,
    evidence_ids: tuple[str, ...],
) -> StagedPlan:
    field = staged.primary_field if staged.phase == "rank" else staged.secondary_field
    values: list[tuple[str, str]] = []
    seen: set[str] = set()
    for row in rows:
        if row.get("dateRange", "current") != "current":
            continue
        label, value = row.get(field), row.get(staged.metric_field)
        if not isinstance(label, str) or not label or len(label) > 300 or value is None:
            raise ValueError("grouped_result_missing_exact_value")
        try:
            number = Decimal(str(value))
        except InvalidOperation as error:
            raise ValueError("grouped_result_invalid_metric") from error
        if not number.is_finite() or label in seen:
            raise ValueError("grouped_result_ambiguous")
        seen.add(label)
        values.append((label, str(value)))
    if staged.phase == "rank":
        values.sort(key=lambda v: (-Decimal(v[1]), v[0]))
        return staged.model_copy(
            update={
                "items": tuple(
                    GroupItem(value=k, total=v)
                    for k, v in values[: staged.request.limit]
                ),
                "phase": "children" if values else "synthesis",
                "rank_evidence_ids": evidence_ids,
                "anchor": AnalysisState(
                    data_source_set_id=state.data_source_set_id, **query_context(state)
                ),
            }
        )
    items = list(staged.items)
    index = next(i for i, item in enumerate(items) if item.status == "pending")
    items[index] = items[index].model_copy(
        update={
            "status": "complete",
            "rows": tuple({field: k, staged.metric_field: v} for k, v in values[:5]),
            "evidence_ids": evidence_ids,
        }
    )
    return staged.model_copy(
        update={
            "items": tuple(items),
            "phase": "children"
            if any(i.status == "pending" for i in items)
            else "synthesis",
        }
    )


def render_progress(staged: StagedPlan) -> str:
    metric = METRIC_LABELS.get(staged.metric_field, staged.metric_field)
    dimension = DIMENSION_LABELS.get(staged.secondary_field, staged.secondary_field)
    lines = [
        "## 段階分析の取得結果",
        "",
        "対象を単独集計で選定 → 対象ごとの内訳 → 差の評価・改善仮説。",
        "",
        "内訳は各対象の上位最大5件です。全件網羅や因果関係は保証しません。",
    ]
    for item in staged.items:
        total = format(Decimal(item.total), ",f")
        difference = Decimal(item.total) - Decimal(staged.items[0].total)
        lines.extend(
            (
                "",
                f"### {text(item.value)}",
                "",
                f"{text(metric)}：{total}"
                f"（先頭対象との差: {format(difference, '+,f')}）",
                "",
                "対象選定の" + evidence(staged.rank_evidence_ids),
                "",
            )
        )
        if item.status == "pending":
            lines.append("内訳は未取得")
        else:
            if item.rows:
                lines.extend(
                    (
                        f"| {cell(dimension)} | {cell(metric)} |",
                        "| --- | ---: |",
                    )
                )
            for row in item.rows:
                lines.append(
                    f"| {cell(row[staged.secondary_field])} | "
                    f"{format(Decimal(row[staged.metric_field]), ',f')} |"
                )
            lines.extend(("", evidence(item.evidence_ids), ""))
            if not item.rows:
                lines.append("  内訳の返却行なし。ゼロや参照元なしとは断定しません。")
    pending = sum(i.status == "pending" for i in staged.items)
    if staged.phase == "rank" or pending:
        lines.append(
            f"未完了の内訳: {pending}対象。"
            "未取得の対象は評価に含めていません。取得済みの条件・根拠・進捗は保存されています。"
        )
    return "\n".join(lines)
